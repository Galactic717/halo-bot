/**
 * Bakes the brand marks the catalogue asks for into one small module.
 *
 * simple-icons ships thousands of icons; shipping the package to the renderer would be absurd for
 * the few dozen we name. This reads the slugs out of host/catalog.ts, pulls just those paths, and
 * writes src/components/brandIcons.ts. Re-run it after adding a plugin with a new `icon:`.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const icons = require('simple-icons/icons.json');
const iconDir = join(dirname(require.resolve('simple-icons/icons.json')), '..', 'icons');
const bySlug = new Map(Object.values(icons).map((icon) => [icon.slug, icon]));

const catalog = readFileSync('host/catalog.ts', 'utf8');
const slugs = [...new Set([...catalog.matchAll(/icon:\s*'([a-z0-9.-]+)'/g)].map((m) => m[1]))].sort();

const found = [];
const missing = [];
for (const slug of slugs) {
  const meta = bySlug.get(slug);
  const file = join(iconDir, `${slug}.svg`);
  // The metadata carries the title and colour; the glyph itself only lives in the .svg.
  const path = existsSync(file) ? /\sd="([^"]+)"/.exec(readFileSync(file, 'utf8'))?.[1] : undefined;
  if (meta && path) found.push([slug, { path, hex: meta.hex }]);
  else missing.push(slug);
}

const lines = [
  '// Generated by scripts/make-brand-icons.mjs — do not edit by hand.',
  `// ${found.length} brand marks from simple-icons, baked in so the renderer ships no icon package.`,
  '',
  'export interface BrandIcon {',
  '  /** Single-path 24x24 glyph. */',
  '  path: string;',
  "  /** The brand's own colour, used to tint the tile. */",
  '  hex: string;',
  '}',
  '',
  'export const BRAND_ICONS: Record<string, BrandIcon> = {',
  ...found.map(([slug, icon]) => `  '${slug}': { path: ${JSON.stringify(icon.path)}, hex: '#${icon.hex}' },`),
  '};',
  '',
];

writeFileSync('src/components/brandIcons.ts', lines.join('\n'), 'utf8');
console.log(`wrote src/components/brandIcons.ts with ${found.length} icons`);
if (missing.length > 0) console.log(`no simple-icons match (monogram fallback): ${missing.join(', ')}`);
